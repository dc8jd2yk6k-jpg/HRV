def load_benchmark(rerun: bool, physionet: bool = False) -> dict[str, pd.DataFrame]:
    out = GEN / "benchmark"
    if rerun or physionet or not (out / "noise_summary.csv").exists():
        source = ["--physionet"] if physionet else ["--mitdb-dir", str(ROOT / "data/external/mitdb_sample")]
        benchmark.main(["--rri", str(RRI), "--out", str(out), *source])
    return {
        "noise": pd.read_csv(out / "noise_summary.csv"),
        "windows": pd.read_csv(out / "noise_windows.csv"),
        "clean": pd.read_csv(out / "clean_summary.csv"),
        "mitdb": pd.read_csv(out / "mitdb_ectopy.csv"),
    }


def load_digitizer(rerun: bool) -> tuple[pd.DataFrame, np.ndarray]:
    out = GEN / "digitizer"
    if rerun or not (out / "charts.csv").exists():
        digitizer_validation.main(["--png", str(PNG), "--out", str(out)])
    return pd.read_csv(out / "charts.csv"), pd.read_csv(out / "value_errors.csv")["value_error_ms"].to_numpy()


def same_window(windows: pd.DataFrame, keep_method: str = "proposed") -> pd.DataFrame:
    key = ["base", "noise", "contamination", "segment", "seed", "window"]
    kept = windows[(windows["method"] == keep_method) & windows["estimate"].notna()][key]
    sub = windows.merge(kept, on=key)
    g = sub.groupby(["base", "noise", "contamination", "method"])["error_pct"]
    t = g.apply(lambda e: float(np.median(np.abs(e.dropna()))) if e.notna().any() else np.nan).unstack("method")
    t["n_windows"] = sub[sub["method"] == keep_method].groupby(["base", "noise", "contamination"]).size()
    return t.reset_index()


def pitfalls(res) -> list[tuple[str, float, str]]:
    """Apparent watch - strap difference under each way of analysing the strap."""
    rec = res.rec
    t0, t1 = res.sleep_s
    a = t0 - rec.start_s
    b = min(t1, rec.start_s + rec.rr_total_s) - rec.start_s
    starts = np.arange(a, b - 300 + 1e-9, 300.0)
    reported = res.watch.reported_avg
    rows = []
    for method, kind in [("none", "naive"), ("kubios_nk2", "naive"), ("malik_delete", "naive"),
                         ("malik_adjacent", "partial"), ("malik_interp", "partial"), ("proposed", "proposed")]:
        strap = np.nanmean(estimate(method, rec.rr_ms, starts))
        label = METHOD_LABELS[method] + (", coverage not matched" if method == "proposed" else "")
        rows.append((label, reported - strap, kind, strap))
    for r in res.by_hypothesis.sort_values("diff_ms").itertuples():
        rows.append((f"Proposed, coverage-matched, clock {r.hypothesis}", r.diff_ms, "proposed", r.strap_avg))
    return rows


