def compile_tex(tex: Path) -> Path:
    if shutil.which("latexmk") is None:
        raise RuntimeError("latexmk not found (install TeX Live with biber)")
    cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "-quiet", tex.name]
    proc = subprocess.run(cmd, cwd=tex.parent, capture_output=True, text=True)
    if proc.returncode != 0:
        log = tex.with_suffix(".log")
        raise RuntimeError(f"LaTeX failed for {tex.name}:\n" + (log.read_text(errors="replace")[-4000:] if log.exists() else proc.stdout[-4000:]))
    log = tex.with_suffix(".log").read_text(errors="replace")
    blg = tex.with_suffix(".blg")
    issues = [line for line in log.splitlines() if line.startswith(("Overfull", "LaTeX Warning", "Package biblatex Warning"))]
    if blg.exists():
        issues += [line for line in blg.read_text(errors="replace").splitlines() if "WARN" in line or "ERROR" in line]
    print(f"{tex.name}: {len(issues)} warning(s)" + "".join(f"\n  {i}" for i in issues))
    subprocess.run(["latexmk", "-c", tex.name], cwd=tex.parent, capture_output=True)
    return tex.with_suffix(".pdf")


