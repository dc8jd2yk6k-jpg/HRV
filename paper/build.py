# Formatting for LaTeX


def num(x, nd=1) -> str:
    if x is None or not np.isfinite(x):
        return "--"
    s = f"{x:,.{nd}f}".replace(",", "{,}")
    return s.replace("-", r"\textminus{}")


def signed(x, nd=1) -> str:
    if x is None or not np.isfinite(x):
        return "--"
    return (f"{x:+.{nd}f}").replace("-", r"\textminus{}")


def pct(x, nd=0) -> str:
    return num(100 * x, nd)


def tex(s: str) -> str:
    """Escape text for LaTeX."""
    for a, b in (("\\", r"\textbackslash{}"), ("%", r"\%"), ("&", r"\&"), ("_", r"\_"), ("#", r"\#")):
        s = s.replace(a, b)
    return s


class Macros:
    def __init__(self):
        self.items: dict[str, str] = {}

    def __setitem__(self, name: str, value: str):
        assert name.isalpha(), name
        self.items[name] = value

    def write(self, path: Path):
        lines = ["% Generated by paper/build.py -- do not edit."]
        lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(self.items.items())]
        path.write_text("\n".join(lines) + "\n")


def tex_table(path: Path, colspec: str, header: list[str], rows: list[list[str]], groups: list[tuple[str, int]] | None = None):
    """booktabs tabular; *groups* inserts \\midrule + a spanning label before row indices."""
    out = [rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    starts = {i: label for label, i in (groups or [])}
    for i, r in enumerate(rows):
        if i in starts:
            if i:
                out.append(r"\midrule")
            out.append(rf"\multicolumn{{{len(header)}}}{{l}}{{\textit{{{starts[i]}}}}} \\")
        out.append(" & ".join(r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(out) + "\n")


def word_count(tex: str, start: str, end: str, macros: dict[str, str]) -> int:
    """Approximate words between two markers: floats, TikZ and citations are
    dropped, number macros count as one word, other commands are stripped."""
    body = tex[tex.index(start) + len(start) : tex.index(end)]
    body = re.sub(r"\\begin\{(figure|table|tikzpicture)\}.*?\\end\{\1\}", " ", body, flags=re.S)
    body = re.sub(r"\\(autocite|label|ref|input|includegraphics)\*?(\[[^\]]*\])?\{[^}]*\}", " ", body)
    body = re.sub(r"\\([A-Za-z]+)", lambda m: " N " if m.group(1) in macros else " ", body)
    body = re.sub(r"[{}$~\\]", " ", body)
    return sum(1 for w in body.split() if re.search(r"[A-Za-z0-9]", w))


